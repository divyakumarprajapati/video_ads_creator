"""
Strategy Engine – the brain of the system.

Takes brand identity + market research + product list and outputs a complete
**CampaignStrategy** containing per-product creative plans and general-brand
creative plans.

Creative decisions (visual style, pacing, layout, video style) are always
deterministic lookup tables.  Messaging text (headlines, CTAs, secondary
messages) is generated by OpenAI when ``OPENAI_API_KEY`` is set, otherwise
falls back to the same deterministic templates.
"""

